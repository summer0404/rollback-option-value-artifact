def rows(name):
    return list(csv.DictReader(open(os.path.join(RES, name))))


def f(x, nd=2):
    return f"{float(x):.{nd}f}"


def pct(x, nd=1):
    return f"{100 * float(x):.{nd}f}"


def num(n):
    return f"{int(n):,}".replace(",", "{,}")


def pfmt(p):
    p = float(p)
    if p < 0.001:
        return "$<$0.001"
    return f"{p:.3f}"


def prel(p):
    """Relation and value for use inside math after p, e.g. $p\\EThreePZeroRollback$."""
    p = float(p)
    return "<0.001" if p < 0.001 else f"={p:.3f}"


class Macros:
    def __init__(self):
        self.m = {}

    def __setitem__(self, k, v):
        assert k.isalpha(), k
        self.m[k] = str(v)

    def write(self, path):
        with open(path, "w") as fh:
            fh.write("% generated by artifact/src/render.py, do not edit\n")
            for k in sorted(self.m):
                fh.write(f"\\newcommand{{\\{k}}}{{{self.m[k]}}}\n")


